// RenderSummary produces the checked-in human-readable view of the normative
// matrix. The JSON matrix remains authoritative.
func RenderSummary(matrix Matrix, fixtures []Fixture) string {
	fixturesByID := map[string]Fixture{}
	for _, fixture := range fixtures {
		fixturesByID[fixture.ID] = fixture
	}
	statusCounts := map[string]int{}
	for _, rule := range matrix.Rules {
		statusCounts[rule.Status]++
	}

	var out strings.Builder
	out.WriteString("# Generated conformance summary\n\n")
	out.WriteString("<!-- Generated by internal/conformance.RenderSummary; edit matrix.json and fixture metadata instead. -->\n\n")
	out.WriteString("The [machine-readable conformance matrix](../internal/compiler/testdata/conformance/matrix.json) is authoritative. This checked-in view is regenerated by `make conformance` and verified by `make docs-check`.\n\n")
	fmt.Fprintf(&out, "Rules: **%d**; fixtures: **%d**; supported: **%d**; intentional divergences: **%d**; incomplete: **%d**.\n\n",
		len(matrix.Rules), len(fixtures), statusCounts["supported"], statusCounts["intentional-divergence"], statusCounts["partial"]+statusCounts["unsupported"]+statusCounts["not-yet-tested"])

	out.WriteString("## COOL Reference Manual checklist\n\n")
	out.WriteString("| Section | Topic | Matrix mapping | Audit rationale |\n")
	out.WriteString("| --- | --- | --- | --- |\n")
	for _, section := range matrix.ManualCoverage {
		mapping := "N/A"
		if section.Applicability == "rules" {
			mapping = strings.Join(section.RuleIDs, ", ")
		}
		fmt.Fprintf(&out, "| %s | %s | %s | %s |\n", markdownCell(section.Section), markdownCell(section.Title), markdownCell(mapping), markdownCell(section.Rationale))
	}

	out.WriteString("\n## Rule evidence\n\n")
	out.WriteString("| Rule | Status | Stage | Fixtures | Evidence | Reference relationship |\n")
	out.WriteString("| --- | --- | --- | ---: | --- | --- |\n")
	for _, rule := range matrix.Rules {
		fixtureIDs := append(append([]string{}, rule.PositiveFixtures...), rule.NegativeFixtures...)
		sort.Strings(fixtureIDs)
		evidence := evidenceKinds(fixtureIDs, fixturesByID)
		if rule.Divergence != nil {
			evidence = append(evidence, "boundary assertion")
		}
		fmt.Fprintf(&out, "| %s | %s | %s | %d | %s | %s |\n",
			markdownCell(rule.ID), markdownCell(rule.Status), markdownCell(rule.ExpectedStage), len(fixtureIDs), markdownCell(strings.Join(evidence, ", ")), markdownCell(rule.ReferenceComparison))
	}

	out.WriteString("\n## Intentional divergences\n\n")
	for _, rule := range matrix.Rules {
		if rule.Divergence == nil {
			continue
		}
		fmt.Fprintf(&out, "### %s — %s\n\n", rule.ID, rule.Name)
		fmt.Fprintf(&out, "- Boundary: %s\n", rule.Divergence.Boundary)
		fmt.Fprintf(&out, "- Reason: %s\n", rule.Divergence.Reason)
		fmt.Fprintf(&out, "- User consequence: %s\n", rule.Divergence.Consequence)
		fmt.Fprintf(&out, "- Scope assertion: %s\n\n", rule.Divergence.Assertion)
	}
	return strings.TrimRight(out.String(), "\n") + "\n"
}

func WriteSummary(root, repoRoot, path string) error {
	matrix, fixtures, err := Load(root, repoRoot)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(RenderSummary(matrix, fixtures)), 0o644)
}

func evidenceKinds(ids []string, fixtures map[string]Fixture) []string {
	kinds := map[string]bool{}
	for _, id := range ids {
		fixture := fixtures[id]
		if len(fixture.ExpectedTokens) > 0 {
			kinds["tokens"] = true
		}
		if len(fixture.ExpectedAST) > 0 {
			kinds["AST/types"] = true
		}
		if len(fixture.ExpectedDiagnostics) > 0 {
			kinds["ordered diagnostics"] = true
		}
		if fixture.ExpectedOutput != "" || fixture.ExpectedRuntimeStatus != "" {
			kinds["runtime output/state"] = true
		}
		if len(fixture.Sources) > 1 || len(fixture.ExpectedSourceUnits) > 0 {
			kinds["source-unit identity"] = true
		}
		if len(fixture.ExpectedArtifacts) > 0 {
			kinds["artifacts"] = true
		}
		if fixture.DebuggerScenario != nil {
			kinds["debugger scenario"] = true
		}
	}
	ordered := []string{"tokens", "AST/types", "ordered diagnostics", "runtime output/state", "source-unit identity", "artifacts", "debugger scenario"}
	var result []string
	for _, kind := range ordered {
		if kinds[kind] {
			result = append(result, kind)
		}
	}
	if len(result) == 0 {
		return []string{"matrix assertion"}
	}
	return result
}

func markdownCell(value string) string {
	value = strings.ReplaceAll(value, "|", "\\|")
	return strings.Join(strings.Fields(value), " ")
}
