package compiler

import (
	"fmt"
	"sort"
)

// MIPSResult is the outcome of MIPS generation.
type MIPSResult struct {
	// OK is false when the program has errors; Assembly is then empty.
	OK          bool              `json:"ok"`
	Assembly    string            `json:"assembly"`
	Diagnostics []Diagnostic      `json:"diagnostics"`
	Classes     []MIPSClassLayout `json:"classes,omitempty"`
}

type mipsGenerator struct {
	options      MIPSOptions
	layout       *mipsProgram
	emit         *mipsEmitter
	ints         map[int32]string
	strings      map[string]string
	stringOrder  []string
	intOrder     []int32
	labelCounter int
}

// GenerateMIPS compiles units through semantic analysis with the selected
// front-end and emits SPIM assembly for the Cool runtime system.
func GenerateMIPS(units []SourceUnit, options MIPSOptions) MIPSResult {
	session := NewProjectCompilationSession(units, ResultContract{Options: CompilationOptions{Frontend: options.Frontend}})
	for session.current != PhaseSemantic && !session.blocked {
		before := session.current
		session.NextPhase()
		if session.current == before {
			break
		}
	}
	result := MIPSResult{Diagnostics: append([]Diagnostic{}, session.result.Diagnostics...)}
	if session.blocked || session.current != PhaseSemantic || hasErrors(session.result.Diagnostics) {
		return result
	}
	files := map[string]string{}
	for _, unit := range units {
		files[unit.ID] = unit.Name
	}
	generator := newMIPSGenerator(buildMIPSLayout(session.program, session.analysis.Table, files), options)
	result.Assembly = generator.generate()
	result.Classes = generator.layout.Layouts()
	result.OK = true
	return result
}

func newMIPSGenerator(layout *mipsProgram, options MIPSOptions) *mipsGenerator {
	return &mipsGenerator{options: options, layout: layout, emit: &mipsEmitter{}, ints: map[int32]string{}, strings: map[string]string{}}
}

func (g *mipsGenerator) intConstant(value int32) string {
	if label, ok := g.ints[value]; ok {
		return label
	}
	label := fmt.Sprintf("int_const%d", len(g.intOrder))
	g.ints[value] = label
	g.intOrder = append(g.intOrder, value)
	return label
}

func (g *mipsGenerator) stringConstant(value string) string {
	if label, ok := g.strings[value]; ok {
		return label
	}
	label := fmt.Sprintf("str_const%d", len(g.stringOrder))
	g.strings[value] = label
	g.stringOrder = append(g.stringOrder, value)
	g.intConstant(int32(len(value)))
	return label
}

func (g *mipsGenerator) newLabel() string {
	label := fmt.Sprintf("label%d", g.labelCounter)
	g.labelCounter++
	return label
}

func (g *mipsGenerator) tag(name string) int { return g.layout.byName[name].tag }

// generate emits the text segment first, collecting the constants it uses,
// then prepends the data segment.
func (g *mipsGenerator) generate() string {
	// Constants every program needs: zero, class names, the empty string,
	// and the source file names used by runtime abort messages.
	g.intConstant(0)
	for _, class := range g.layout.classes {
		g.stringConstant(class.name)
	}
	g.stringConstant("")
	g.intConstant(0)
	files := make([]string, 0, len(g.layout.files))
	for _, name := range g.layout.files {
		files = append(files, name)
	}
	sort.Strings(files)
	for _, name := range files {
		g.stringConstant(name)
	}

	text := &mipsEmitter{}
	data := g.emit
	g.emit = text
	g.emitText()
	g.emit = data

	g.emit.comment("Generated by Cooler Compiler for SPIM with the Cool runtime (trap.handler).")
	g.emit.comment("Memory manager: %s", g.memoryManagerName())
	g.emitDataHeader()
	g.emitConstants()
	g.emitTables()
	g.emitPrototypes()
	g.emitHeapStart()
	return g.emit.out.String() + text.out.String()
}

func (g *mipsGenerator) memoryManagerName() string {
	name := "NoGC"
	if g.options.GC.Generational {
		name = "GenGC (-g)"
	}
	if g.options.GC.Test {
		name += ", collect at every allocation (-t)"
	}
	if g.options.GC.Debug {
		name += ", header checks (-T)"
	}
	return name
}

// emitDataHeader writes the globals and memory-manager words the runtime
// reads: the basic-class tags and the collector selected by -g / -t.
func (g *mipsGenerator) emitDataHeader() {
	g.emit.directive(".data")
	g.emit.directive(".align", 2)
	for _, name := range []string{"class_nameTab", "Main_protObj", "Int_protObj", "String_protObj", "bool_const0", "bool_const1", "_int_tag", "_bool_tag", "_string_tag"} {
		g.emit.directive(".globl", name)
	}
	for _, basic := range []struct{ label, class string }{{"_int_tag", typeInt}, {"_bool_tag", typeBool}, {"_string_tag", typeString}} {
		g.emit.label(basic.label)
		g.emit.directive(".word", g.tag(basic.class))
	}
	initializer, collector := "_NoGC_Init", "_NoGC_Collect"
	if g.options.GC.Generational {
		initializer, collector = "_GenGC_Init", "_GenGC_Collect"
	}
	test := 0
	if g.options.GC.Test {
		test = 1
	}
	g.emit.directive(".globl", "_MemMgr_INITIALIZER")
	g.emit.label("_MemMgr_INITIALIZER")
	g.emit.directive(".word", initializer)
	g.emit.directive(".globl", "_MemMgr_COLLECTOR")
	g.emit.label("_MemMgr_COLLECTOR")
	g.emit.directive(".word", collector)
	g.emit.directive(".globl", "_MemMgr_TEST")
	g.emit.label("_MemMgr_TEST")
	g.emit.directive(".word", test)
}

func (g *mipsGenerator) emitHeapStart() {
	g.emit.directive(".globl", "heap_start")
	g.emit.label("heap_start")
	g.emit.directive(".word", 0)
}
