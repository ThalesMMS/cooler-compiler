package compiler

import "fmt"

func (vm *VM) executeNew(frame *vmFrame, instruction byteInstruction) {
	typeName := instruction.Text
	if typeName == typeSelf {
		typeName = frame.self.typeName()
	}
	value, ok := vm.allocate(typeName, instruction.Span)
	if !ok {
		return
	}
	initializer := vm.exec.Methods[methodKey(typeName, "$init")]
	if initializer == nil {
		vm.fail("COL6017", "missing initializer for "+typeName, "Regenerate the program bytecode.", instruction.Span)
		return
	}
	vm.startCompiledCall(initializer, value, nil, instruction.Span)
}

func (vm *VM) allocate(typeName string, span Span) (runtimeValueInternal, bool) {
	switch typeName {
	case typeInt:
		return intValue(0), true
	case typeString:
		return stringValue(""), true
	case typeBool:
		return boolValue(false), true
	}
	class := vm.exec.Classes[typeName]
	if class == nil {
		vm.fail("COL6018", "cannot allocate unknown class "+typeName, "Declare the class before using new.", span)
		return voidValue(), false
	}
	if vm.objectCount >= maxVMObjects {
		vm.fail("COL6019", "VM object allocation limit exceeded", "Reduce allocation in loops or recursion.", span)
		return voidValue(), false
	}
	object := &runtimeObject{id: vm.nextObjectID, class: typeName, fields: map[string]runtimeValueInternal{}}
	vm.nextObjectID++
	vm.objectCount++
	for _, attr := range class.Attributes {
		object.fields[attr.Name] = defaultRuntimeValue(attr.TypeName)
	}
	return objectValue(object), true
}

func defaultRuntimeValue(typeName string) runtimeValueInternal {
	switch typeName {
	case typeInt:
		return intValue(0)
	case typeString:
		return stringValue("")
	case typeBool:
		return boolValue(false)
	default:
		return voidValue()
	}
}

func (vm *VM) executeCall(instruction byteInstruction) {
	args := make([]runtimeValueInternal, instruction.ArgCount)
	for i := instruction.ArgCount - 1; i >= 0; i-- {
		value, ok := vm.pop(instruction.Span)
		if !ok {
			return
		}
		args[i] = value
	}
	receiver, ok := vm.pop(instruction.Span)
	if !ok {
		return
	}
	if receiver.isVoid() {
		vm.fail("COL6020", "dispatch on void", "Ensure the receiver is initialized before calling a method.", instruction.Span)
		return
	}
	if instruction.Text == "$init" {
		owner := instruction.StaticType
		if owner == "" {
			owner = receiver.typeName()
		}
		method := vm.exec.Methods[methodKey(owner, "$init")]
		if method == nil {
			vm.fail("COL6021", "missing initializer "+owner+".$init", "Regenerate the program bytecode.", instruction.Span)
			return
		}
		vm.startCompiledCall(method, receiver, args, instruction.Span)
		return
	}
	lookupType := receiver.typeName()
	if instruction.StaticType != "" {
		lookupType = instruction.StaticType
	}
	info, found := vm.exec.Table.LookupMethod(lookupType, instruction.Text)
	if !found {
		vm.fail("COL6022", fmt.Sprintf("method %s is unavailable on %s", instruction.Text, lookupType), "Check the receiver and method name.", instruction.Span)
		return
	}
	if info.Builtin {
		result, ok := vm.executeBuiltin(info, receiver, args, instruction.Span)
		if ok {
			vm.push(result, instruction.Span)
		}
		return
	}
	method := vm.exec.Methods[methodKey(info.Owner, info.Name)]
	if method == nil {
		vm.fail("COL6023", "compiled body is missing for "+methodKey(info.Owner, info.Name), "Regenerate the program bytecode.", instruction.Span)
		return
	}
	vm.startCompiledCall(method, receiver, args, instruction.Span)
}

func (vm *VM) startCompiledCall(method *compiledMethod, receiver runtimeValueInternal, args []runtimeValueInternal, span Span) {
	if len(vm.frames) >= maxVMFrames {
		vm.fail("COL6024", "VM call stack limit exceeded", "Reduce recursive call depth.", span)
		return
	}
	if len(args) != len(method.Formals) {
		vm.fail("COL6025", fmt.Sprintf("%s expected %d arguments but received %d", method.DisplayName, len(method.Formals), len(args)), "The semantic analyzer should enforce method arity.", span)
		return
	}
	locals := map[string]runtimeValueInternal{}
	for i, name := range method.Formals {
		locals[name] = args[i]
	}
	vm.frames = append(vm.frames, &vmFrame{
		method: method, self: receiver, scopes: []map[string]runtimeValueInternal{locals},
		stackBase: len(vm.stack),
	})
}

func (vm *VM) executeReturn(instruction byteInstruction) {
	value, ok := vm.pop(instruction.Span)
	if !ok {
		return
	}
	if len(vm.frames) == 0 {
		vm.fail("COL6026", "return with an empty call stack", "This indicates invalid generated bytecode.", instruction.Span)
		return
	}
	frame := vm.frames[len(vm.frames)-1]
	if frame.stackBase < 0 || frame.stackBase > len(vm.stack) {
		vm.fail("COL6027", "invalid return stack base", "This indicates invalid generated bytecode.", instruction.Span)
		return
	}
	vm.stack = vm.stack[:frame.stackBase]
	vm.frames = vm.frames[:len(vm.frames)-1]
	if len(vm.frames) == 0 {
		vm.halted = true
		vm.push(value, instruction.Span)
		return
	}
	vm.push(value, instruction.Span)
}

func (vm *VM) executeCase(frame *vmFrame, instruction byteInstruction) {
	value, ok := vm.pop(instruction.Span)
	if !ok {
		return
	}
	if value.isVoid() {
		vm.fail("COL6030", "case on void", "Ensure the case expression produces an object.", instruction.Span)
		return
	}
	runtimeType := value.typeName()
	bestDistance := int(^uint(0) >> 1)
	var selected *caseTarget
	for i := range instruction.Cases {
		target := &instruction.Cases[i]
		if distance, conforms := vm.exec.Table.Distance(runtimeType, target.Type); conforms && distance < bestDistance {
			selected = target
			bestDistance = distance
		}
	}
	if selected == nil {
		vm.fail("COL6031", "no matching case branch for "+runtimeType, "Add a branch for the runtime type or one of its ancestors.", instruction.Span)
		return
	}
	if selected.Target < 0 || selected.Target >= len(frame.method.Code) {
		vm.fail("COL6032", "invalid case branch target", "This indicates invalid generated bytecode.", instruction.Span)
		return
	}
	frame.scopes = append(frame.scopes, map[string]runtimeValueInternal{selected.Name: value})
	frame.ip = selected.Target
	vm.lastNote = fmt.Sprintf("selected %s : %s", selected.Name, selected.Type)
}
