package compiler

import "fmt"

func (vm *VM) push(value runtimeValueInternal, span Span) bool {
	vm.ensurePolicy()
	if len(vm.stack) >= vm.policy.MaxOperandStackDepth {
		vm.fail("COL6010", "VM operand stack limit exceeded", "Reduce expression or recursion depth.", span)
		return false
	}
	vm.stack = append(vm.stack, value)
	return true
}

func (vm *VM) pop(span Span) (runtimeValueInternal, bool) {
	if len(vm.stack) == 0 {
		vm.fail("COL6011", "VM operand stack underflow", "This indicates invalid generated bytecode.", span)
		return voidValue(), false
	}
	value := vm.stack[len(vm.stack)-1]
	vm.stack = vm.stack[:len(vm.stack)-1]
	return value, true
}

func (vm *VM) popTwo(span Span) (runtimeValueInternal, runtimeValueInternal, bool) {
	if len(vm.stack) < 2 {
		vm.fail("COL6011", "VM operand stack underflow", "This indicates invalid generated bytecode.", span)
		return voidValue(), voidValue(), false
	}
	start := len(vm.stack) - 2
	left, right := vm.stack[start], vm.stack[start+1]
	vm.stack[start] = runtimeValueInternal{}
	vm.stack[start+1] = runtimeValueInternal{}
	vm.stack = vm.stack[:start]
	return left, right, true
}

func (vm *VM) loadName(frame *vmFrame, name string, span Span) {
	if value, found := frame.lookup(name); found {
		vm.push(value, span)
		return
	}
	if frame.self.kind == valueObject && frame.self.o != nil {
		if value, found := frame.self.o.fields[name]; found {
			vm.push(value, span)
			return
		}
	}
	vm.fail("COL6012", fmt.Sprintf("runtime lookup could not find %s", name), "The semantic analyzer should resolve every identifier.", span)
}

func (vm *VM) storeName(frame *vmFrame, name string, value runtimeValueInternal, span Span) {
	if frame.store(name, value) {
		return
	}
	if frame.self.kind == valueObject && frame.self.o != nil {
		if _, found := frame.self.o.fields[name]; found {
			frame.self.o.fields[name] = value
			return
		}
	}
	vm.fail("COL6013", fmt.Sprintf("runtime assignment could not find %s", name), "The semantic analyzer should resolve every assignment target.", span)
}

func (vm *VM) executeIntegerBinary(instruction byteInstruction) {
	left, right, ok := vm.popTwo(instruction.Span)
	if !ok {
		return
	}
	if left.kind != valueInt || right.kind != valueInt {
		vm.fail("COL6014", fmt.Sprintf("%s received %s and %s", instruction.Op, left.typeName(), right.typeName()), "Arithmetic and ordering operators require Int operands.", instruction.Span)
		return
	}
	switch instruction.Op {
	case opAdd:
		vm.push(intValue(left.i.add(right.i)), instruction.Span)
	case opSub:
		vm.push(intValue(left.i.subtract(right.i)), instruction.Span)
	case opMul:
		vm.push(intValue(left.i.multiply(right.i)), instruction.Span)
	case opDiv:
		result, valid := left.i.divide(right.i)
		if !valid {
			vm.fail("COL6015", "division by zero", "Guard the divisor before evaluating '/'.", instruction.Span)
			return
		}
		vm.push(intValue(result), instruction.Span)
	case opLess:
		vm.push(boolValue(left.i.less(right.i)), instruction.Span)
	case opLessEqual:
		vm.push(boolValue(left.i.lessEqual(right.i)), instruction.Span)
	}
}

func (vm *VM) executeEqual(instruction byteInstruction) {
	left, right, ok := vm.popTwo(instruction.Span)
	if !ok {
		return
	}
	equal := false
	if left.isVoid() || right.isVoid() {
		equal = left.isVoid() && right.isVoid()
	} else if left.kind == right.kind {
		switch left.kind {
		case valueInt:
			equal = left.i.equal(right.i)
		case valueString:
			equal = left.s == right.s
		case valueBool:
			equal = left.b == right.b
		case valueObject:
			equal = left.o == right.o
		}
	}
	vm.push(boolValue(equal), instruction.Span)
}

func (vm *VM) jump(frame *vmFrame, target int, span Span) {
	if target < 0 || target >= len(frame.method.Code) {
		vm.fail("COL6016", fmt.Sprintf("invalid jump target %d", target), "This indicates invalid generated bytecode.", span)
		return
	}
	frame.ip = target
}
