const verifierMutationProgram = `class Main inherits IO {
  helper(x : Int) : Int {
    let y : Int <- x in
      if y < 2 then y + 1 else y - 1 fi
  };
  main() : Object { out_int(helper(1)) };
};`

const verifierCaseProgram = `class Main {
  main() : Object {
    case new Main of
      value : Main => value;
    esac
  };
};`

func TestVerifierAcceptsGeneratedExecutableAndDocumentsEveryOpcode(t *testing.T) {
	exec := verifierTestExecutable(t, verifierMutationProgram)
	if diagnostics := verifyExecutable(exec); hasErrors(diagnostics) {
		t.Fatalf("valid generated bytecode failed verification: %+v", diagnostics)
	}
	all := []opcode{
		opPushInt, opPushString, opPushBool, opPushVoid, opLoadSelf, opLoad,
		opStore, opDup, opPop, opEnterScope, opExitScopeKeep, opBind,
		opAdd, opSub, opMul, opDiv, opNeg, opNot, opLess, opLessEqual,
		opEqual, opIsVoid, opJump, opJumpIfFalse, opNew, opCall, opReturn,
		opCaseSelect, opHalt,
	}
	if len(verifierOpcodeSemantics) != len(all) {
		t.Fatalf("opcode semantics has %d entries, want %d", len(verifierOpcodeSemantics), len(all))
	}
	for _, operation := range all {
		semantics, found := verifierOpcodeSemantics[operation]
		if !found || semantics.Stack == "" || semantics.ControlFlow == "" {
			t.Fatalf("opcode %s has no complete verifier semantics: %+v", operation, semantics)
		}
	}
}

func TestVerifierAcceptsHandConstructedExecutable(t *testing.T) {
	span := emptySpan()
	objectInfo := &ClassInfo{Name: typeObject, Attributes: map[string]*AttrInfo{}, Methods: map[string]*MethodInfo{}}
	mainMethodInfo := &MethodInfo{Name: "main", Owner: "Main", ReturnType: typeObject, Span: span}
	mainInfo := &ClassInfo{
		Name: "Main", Parent: typeObject, Attributes: map[string]*AttrInfo{},
		Methods: map[string]*MethodInfo{"main": mainMethodInfo}, MethodOrder: []string{"main"},
	}
	table := &ClassTable{Classes: map[string]*ClassInfo{typeObject: objectInfo, "Main": mainInfo}, Order: []string{typeObject, "Main"}}
	objectInit := &compiledMethod{Owner: typeObject, Name: "$init", DisplayName: "Object.$init", ReturnType: typeSelf, Synthetic: true, Span: span, Code: []byteInstruction{{Op: opLoadSelf, Span: span}, {Op: opReturn, Span: span}}}
	mainInit := &compiledMethod{Owner: "Main", Name: "$init", DisplayName: "Main.$init", ReturnType: typeSelf, Synthetic: true, Span: span, Code: []byteInstruction{{Op: opLoadSelf, Span: span}, {Op: opReturn, Span: span}}}
	mainMethod := &compiledMethod{Owner: "Main", Name: "main", DisplayName: "Main.main", ReturnType: typeObject, Span: span, Code: []byteInstruction{{Op: opPushVoid, Span: span}, {Op: opReturn, Span: span}}}
	entry := &compiledMethod{Owner: "$program", Name: "$entry", DisplayName: "$program.$entry", ReturnType: typeObject, Synthetic: true, Span: span, Code: []byteInstruction{{Op: opNew, Text: "Main", Span: span}, {Op: opCall, Text: "main", Span: span, OperandSpan: span}, {Op: opHalt, Span: span}}}
	exec := &executable{
		Table: table,
		Classes: map[string]*runtimeClass{
			typeObject: {Name: typeObject},
			"Main":     {Name: "Main", Parent: typeObject},
		},
		Methods: map[string]*compiledMethod{
			methodKey(typeObject, "$init"):  objectInit,
			methodKey("Main", "$init"):      mainInit,
			methodKey("Main", "main"):       mainMethod,
			methodKey("$program", "$entry"): entry,
		},
		MethodOrder: []*compiledMethod{objectInit, mainInit, mainMethod, entry}, Entry: entry,
	}
	rebuildVerifierMetadata(exec)
	if diagnostics := verifyExecutable(exec); hasErrors(diagnostics) {
		t.Fatalf("hand-constructed executable failed verification: %+v", diagnostics)
	}
}

func TestVerifierRejectsMutatedGeneratedBytecode(t *testing.T) {
	tests := []struct {
		name   string
		code   string
		source string
		mutate func(*testing.T, *executable)
	}{
		{
			name: "bad jump target", code: "COL5102", source: verifierMutationProgram,
			mutate: func(t *testing.T, exec *executable) {
				method := verifierMethod(t, exec, "Main.helper")
				index := verifierInstruction(t, method, opJumpIfFalse, "")
				method.Code[index].Target = len(method.Code)
			},
		},
		{
			name: "stack underflow", code: "COL5103", source: verifierMutationProgram,
			mutate: func(t *testing.T, exec *executable) {
				method := verifierMethod(t, exec, "Main.helper")
				method.Code[0] = byteInstruction{Op: opPop, Span: method.Code[0].Span}
			},
		},
		{
			name: "inconsistent merge height", code: "COL5104", source: verifierMutationProgram,
			mutate: func(t *testing.T, exec *executable) {
				method := verifierMethod(t, exec, "Main.helper")
				jump := verifierInstruction(t, method, opJump, "")
				insertVerifierInstruction(method, jump, byteInstruction{Op: opPushInt, Span: method.Code[jump].Span})
			},
		},
		{
			name: "wrong condition category", code: "COL5105", source: verifierMutationProgram,
			mutate: func(t *testing.T, exec *executable) {
				method := verifierMethod(t, exec, "Main.helper")
				condition := verifierInstruction(t, method, opLess, "")
				method.Code[condition].Op = opAdd
			},
		},
		{
			name: "unbalanced scope", code: "COL5106", source: verifierMutationProgram,
			mutate: func(t *testing.T, exec *executable) {
				method := verifierMethod(t, exec, "Main.helper")
				exit := verifierInstruction(t, method, opExitScopeKeep, "")
				method.Code[exit].Op = opDup
			},
		},
		{
			name: "invalid storage", code: "COL5107", source: verifierMutationProgram,
			mutate: func(t *testing.T, exec *executable) {
				method := verifierMethod(t, exec, "Main.helper")
				load := verifierInstruction(t, method, opLoad, "x")
				method.Code[load].Text = "missing"
			},
		},
		{
			name: "bad call arity", code: "COL5108", source: verifierMutationProgram,
			mutate: func(t *testing.T, exec *executable) {
				method := verifierMethod(t, exec, "Main.main")
				call := verifierInstruction(t, method, opCall, "out_int")
				method.Code[call].ArgCount = 0
			},
		},
		{
			name: "missing return", code: "COL5109", source: verifierMutationProgram,
			mutate: func(t *testing.T, exec *executable) {
				method := verifierMethod(t, exec, "Main.helper")
				last := len(method.Code) - 1
				method.Code[last].Op = opPop
			},
		},
		{
			name: "unreachable instruction", code: "COL5110", source: verifierMutationProgram,
			mutate: func(t *testing.T, exec *executable) {
				method := verifierMethod(t, exec, "Main.helper")
				method.Code = append(method.Code, byteInstruction{Op: opPushInt, Span: method.Span})
			},
		},
		{
			name: "unknown opcode", code: "COL5101", source: verifierMutationProgram,
			mutate: func(t *testing.T, exec *executable) {
				method := verifierMethod(t, exec, "Main.helper")
				method.Code[0].Op = opcode("MUTATED")
			},
		},
		{
			name: "bad case target", code: "COL5102", source: verifierCaseProgram,
			mutate: func(t *testing.T, exec *executable) {
				method := verifierMethod(t, exec, "Main.main")
				selection := verifierInstruction(t, method, opCaseSelect, "")
				method.Code[selection].Cases[0].Target = len(method.Code)
			},
		},
		{
			name: "duplicate method key", code: "COL5111", source: verifierMutationProgram,
			mutate: func(t *testing.T, exec *executable) {
				method := verifierMethod(t, exec, "Main.helper")
				exec.MethodOrder = append(exec.MethodOrder, method)
			},
		},
		{
			name: "mismatched method metadata", code: "COL5112", source: verifierMutationProgram,
			mutate: func(t *testing.T, exec *executable) {
				method := verifierMethod(t, exec, "Main.helper")
				method.ReturnType = typeObject
			},
		},
		{
			name: "invalid span", code: "COL5113", source: verifierMutationProgram,
			mutate: func(t *testing.T, exec *executable) {
				method := verifierMethod(t, exec, "Main.helper")
				method.Code[0].Span.StartLine = 0
			},
		},
		{
			name: "missing initializer", code: "COL5114", source: verifierMutationProgram,
			mutate: func(t *testing.T, exec *executable) {
				delete(exec.Methods, methodKey("Main", "$init"))
			},
		},
	}

	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			exec := verifierTestExecutable(t, test.source)
			test.mutate(t, exec)
			rebuildVerifierMetadata(exec)
			diagnostics := verifyExecutable(exec)
			if !verifierHasCode(diagnostics, test.code) {
				t.Fatalf("missing %s after mutation; diagnostics: %+v", test.code, diagnostics)
			}
			for _, diagnostic := range diagnostics {
				if !validVerifierSpan(diagnostic.Span) {
					t.Fatalf("verifier diagnostic has malformed span: %+v", diagnostic)
				}
				if diagnostic.Code == test.code && (diagnostic.Stage != "codegen" || diagnostic.Severity != SeverityError || diagnostic.Message == "" || diagnostic.Hint == "") {
					t.Fatalf("unstable verifier diagnostic shape: %+v", diagnostic)
				}
			}
		})
	}
}

func TestVerifierCrossValidatesIRAssemblyAndCFGMetadata(t *testing.T) {
	for _, test := range []struct {
		name   string
		mutate func(*executable)
	}{
		{"IR", func(exec *executable) { exec.IR[0].Index++ }},
		{"assembly", func(exec *executable) { exec.Assembly[0] += " mutated" }},
		{"assembly span", func(exec *executable) { exec.AssemblySpans[0].StartColumn++ }},
		{"CFG", func(exec *executable) { exec.ControlFlow.Blocks[0].End++ }},
	} {
		t.Run(test.name, func(t *testing.T) {
			exec := verifierTestExecutable(t, verifierMutationProgram)
			test.mutate(exec)
			if diagnostics := verifyExecutable(exec); !verifierHasCode(diagnostics, "COL5112") {
				t.Fatalf("metadata mutation was accepted: %+v", diagnostics)
			}
		})
	}
}

func TestInvalidExecutableCannotStartOrResetVM(t *testing.T) {
	exec := verifierTestExecutable(t, verifierMutationProgram)
	method := verifierMethod(t, exec, "Main.helper")
	method.Code[0].Op = opcode("MUTATED")
	rebuildVerifierMetadata(exec)
	exec.verified = false
	vm := newVM(exec)
	if !vm.halted || vm.executed != 0 || len(vm.frames) != 0 || !verifierHasCode(vm.diagnostics, "COL5101") {
		t.Fatalf("invalid executable started: %+v", vm)
	}
	if !strings.Contains(vm.diagnostics[0].Message, "Main.helper at instruction 0") || vm.diagnostics[0].Span != method.Code[0].Span {
		t.Fatalf("verifier report omitted stable location: %+v", vm.diagnostics[0])
	}
	session := &DebugSession{exec: exec, blocked: true, base: Result{Diagnostics: vm.diagnostics}}
	snapshot := session.Reset()
	if session.vm != nil || snapshot.Status != "blocked" || snapshot.Runtime.ExecutedSteps != 0 {
		t.Fatalf("blocked session created a VM: %+v", snapshot)
	}
}

func TestCodegenVerificationBlocksRuntimePhase(t *testing.T) {
	exec := verifierTestExecutable(t, verifierMutationProgram)
	method := verifierMethod(t, exec, "Main.helper")
	method.Code[0].Op = opcode("MUTATED")
	materializeIR(exec)
	session := &CompilationSession{
		exec: exec, current: PhaseIR,
		result: newResult("", ResultContract{}),
	}
	snapshot := session.NextPhase()
	if !snapshot.Blocked || snapshot.CurrentPhase != PhaseCodegen || !verifierHasCode(snapshot.Result.Diagnostics, "COL5101") {
		t.Fatalf("codegen did not block on verifier failure: %+v", snapshot)
	}
	if session.debug == nil || session.debug.vm != nil || !session.debug.blocked {
		t.Fatalf("verifier failure prepared a VM: %+v", session.debug)
	}
	after := session.NextPhase()
	if after.CurrentPhase != PhaseCodegen || !after.Blocked {
		t.Fatalf("blocked pipeline advanced to runtime: %+v", after)
	}
}

func FuzzBytecodeVerifier(f *testing.F) {
	f.Add(verifierMutationProgram, []byte{0, 1, 2, 3, 4})
	f.Add(verifierMutationProgram, []byte{255, 13, 42, 99})
	regressionData, err := os.ReadFile(filepath.Join("testdata", "fuzz-regressions", "verifier-invalid-diagnostic-span.json"))
	if err != nil {
		f.Fatalf("read verifier fuzz regression: %v", err)
	}
	var regression struct {
		Source    string `json:"source"`
		Mutations []byte `json:"mutations"`
	}
	if err := json.Unmarshal(regressionData, &regression); err != nil {
		f.Fatalf("decode verifier fuzz regression: %v", err)
	}
	f.Add(regression.Source, regression.Mutations)
	addCompilerFuzzSourceSeeds(f, func(source string) { f.Add(source, []byte{0, 7, 13}) })
	f.Fuzz(func(t *testing.T, source string, mutations []byte) {
		if len(source) > fuzzMaxSourceBytes || len(mutations) > fuzzMaxMutationBytes {
			t.Skip()
		}
		tokens, lexDiagnostics := LexSource("fuzz-verifier", source)
		program, parseDiagnostics := Parse(tokens)
		if program == nil || hasErrors(append(lexDiagnostics, parseDiagnostics...)) {
			return
		}
		analysis := Analyze(program)
		if hasErrors(analysis.Diagnostics) {
			return
		}
		exec := generateExecutable(program, analysis)
		rebuildVerifierMetadata(exec)
		if hasErrors(verifyExecutable(exec)) || len(exec.MethodOrder) == 0 {
			t.Fatal("valid compiler output failed bytecode verification")
		}
		method := exec.MethodOrder[int(mutationsByte(mutations, 0))%len(exec.MethodOrder)]
		for index, mutation := range mutations {
			if len(method.Code) == 0 {
				break
			}
			instruction := &method.Code[index%len(method.Code)]
			switch mutation % 8 {
			case 0:
				instruction.Op = opcode("FUZZ")
			case 1:
				instruction.Target = int(int8(mutation))
			case 2:
				instruction.ArgCount = int(mutation % 16)
			case 3:
				instruction.Text = ""
			case 4:
				instruction.Span.StartLine = int(mutation % 3)
			case 5:
				instruction.ValueType = "MissingType"
			case 6:
				instruction.Cases = append(instruction.Cases, caseTarget{Target: int(mutation), Type: "MissingType"})
			case 7:
				instruction.StaticType = "MissingType"
			}
		}
		rebuildVerifierMetadata(exec)
		first := verifyExecutable(exec)
		second := verifyExecutable(exec)
		if !reflect.DeepEqual(first, second) {
			t.Fatal("bytecode verifier diagnostics are nondeterministic")
		}
		for _, diagnostic := range first {
			if !validVerifierSpan(diagnostic.Span) {
				t.Fatalf("verifier produced malformed diagnostic span: %+v", diagnostic)
			}
		}
	})
}

func verifierTestExecutable(t testing.TB, source string) *executable {
	t.Helper()
	tokens, lexerDiagnostics := LexSource("verifier-test", source)
	program, parserDiagnostics := Parse(tokens)
	diagnostics := append(append([]Diagnostic(nil), lexerDiagnostics...), parserDiagnostics...)
	if hasErrors(diagnostics) || program == nil {
		t.Fatalf("verifier test source did not parse: %+v", diagnostics)
	}
	analysis := Analyze(program)
	if hasErrors(analysis.Diagnostics) {
		t.Fatalf("verifier test source did not analyze: %+v", analysis.Diagnostics)
	}
	exec := generateExecutable(program, analysis)
	rebuildVerifierMetadata(exec)
	if diagnostics := verifyExecutable(exec); hasErrors(diagnostics) {
		t.Fatalf("verifier test fixture is invalid: %+v", diagnostics)
	}
	return exec
}

func rebuildVerifierMetadata(exec *executable) {
	materializeIR(exec)
	materializeAssembly(exec)
	exec.verified = false
}

func verifierMethod(t testing.TB, exec *executable, displayName string) *compiledMethod {
	t.Helper()
	for _, method := range exec.MethodOrder {
		if method != nil && method.DisplayName == displayName {
			return method
		}
	}
	t.Fatalf("missing method %s", displayName)
	return nil
}

func verifierInstruction(t testing.TB, method *compiledMethod, operation opcode, text string) int {
	t.Helper()
	for index, instruction := range method.Code {
		if instruction.Op == operation && (text == "" || instruction.Text == text) {
			return index
		}
	}
	t.Fatalf("missing %s %q in %s", operation, text, method.DisplayName)
	return -1
}

func insertVerifierInstruction(method *compiledMethod, index int, instruction byteInstruction) {
	for codeIndex := range method.Code {
		if (method.Code[codeIndex].Op == opJump || method.Code[codeIndex].Op == opJumpIfFalse) && method.Code[codeIndex].Target >= index {
			method.Code[codeIndex].Target++
		}
		for caseIndex := range method.Code[codeIndex].Cases {
			if method.Code[codeIndex].Cases[caseIndex].Target >= index {
				method.Code[codeIndex].Cases[caseIndex].Target++
			}
		}
	}
	method.Code = append(method.Code, byteInstruction{})
	copy(method.Code[index+1:], method.Code[index:])
	method.Code[index] = instruction
}

func verifierHasCode(diagnostics []Diagnostic, code string) bool {
	for _, diagnostic := range diagnostics {
		if diagnostic.Code == code {
			return true
		}
	}
	return false
}
