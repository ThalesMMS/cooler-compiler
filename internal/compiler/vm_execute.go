package compiler

func (vm *VM) executeOne() {
	if vm.halted {
		return
	}
	if vm.executed >= defaultVMMaxSteps {
		vm.fail("COL6002", "VM instruction limit exceeded", "Reduce the loop or recursion depth.", vm.nextSpan())
		return
	}
	frame := vm.currentFrame()
	if frame == nil {
		vm.halted = true
		vm.record("HALT", emptySpan(), "no frames remain")
		return
	}
	if frame.ip < 0 || frame.ip >= len(frame.method.Code) {
		vm.fail("COL6001", "instruction pointer escaped method "+frame.method.DisplayName, "This indicates invalid generated bytecode.", frame.method.Span)
		return
	}
	instruction := frame.method.Code[frame.ip]
	methodName := frame.method.DisplayName
	frame.ip++
	vm.executed++
	vm.lastInstruction = instruction
	vm.lastMethod = methodName
	vm.lastNote = instruction.Comment

	switch instruction.Op {
	case opPushInt:
		vm.push(intValue(instruction.Int), instruction.Span)
	case opPushString:
		vm.push(stringValue(instruction.Text), instruction.Span)
	case opPushBool:
		vm.push(boolValue(instruction.Bool), instruction.Span)
	case opPushVoid:
		vm.push(voidValue(), instruction.Span)
	case opLoadSelf:
		vm.push(frame.self, instruction.Span)
	case opLoad:
		vm.loadName(frame, instruction.Text, instruction.Span)
	case opStore:
		value, ok := vm.pop(instruction.Span)
		if ok {
			vm.storeName(frame, instruction.Text, value, instruction.Span)
		}
	case opDup:
		if len(vm.stack) == 0 {
			vm.fail("COL6003", "cannot duplicate an empty operand stack", "This indicates invalid generated bytecode.", instruction.Span)
		} else {
			vm.push(vm.stack[len(vm.stack)-1], instruction.Span)
		}
	case opPop:
		_, _ = vm.pop(instruction.Span)
	case opEnterScope:
		frame.scopes = append(frame.scopes, map[string]runtimeValueInternal{})
	case opExitScopeKeep:
		value, ok := vm.pop(instruction.Span)
		if ok {
			if len(frame.scopes) <= 1 {
				vm.fail("COL6004", "cannot leave the root local scope", "This indicates invalid generated bytecode.", instruction.Span)
			} else {
				frame.scopes = frame.scopes[:len(frame.scopes)-1]
				vm.push(value, instruction.Span)
			}
		}
	case opBind:
		value, ok := vm.pop(instruction.Span)
		if ok {
			if len(frame.scopes) == 0 {
				frame.scopes = append(frame.scopes, map[string]runtimeValueInternal{})
			}
			frame.scopes[len(frame.scopes)-1][instruction.Text] = value
		}
	case opAdd, opSub, opMul, opDiv, opLess, opLessEqual:
		vm.executeIntegerBinary(instruction)
	case opEqual:
		vm.executeEqual(instruction)
	case opNeg:
		value, ok := vm.pop(instruction.Span)
		if ok {
			if value.kind != valueInt {
				vm.fail("COL6005", "integer complement received "+value.typeName(), "Only Int values can be used with '~'.", instruction.Span)
			} else {
				vm.push(intValue(-value.i), instruction.Span)
			}
		}
	case opNot:
		value, ok := vm.pop(instruction.Span)
		if ok {
			if value.kind != valueBool {
				vm.fail("COL6006", "Boolean complement received "+value.typeName(), "Only Bool values can be used with 'not'.", instruction.Span)
			} else {
				vm.push(boolValue(!value.b), instruction.Span)
			}
		}
	case opIsVoid:
		value, ok := vm.pop(instruction.Span)
		if ok {
			vm.push(boolValue(value.isVoid()), instruction.Span)
		}
	case opJump:
		vm.jump(frame, instruction.Target, instruction.Span)
	case opJumpIfFalse:
		condition, ok := vm.pop(instruction.Span)
		if ok {
			if condition.kind != valueBool {
				vm.fail("COL6007", "conditional jump received "+condition.typeName(), "A COOL condition must evaluate to Bool.", instruction.Span)
			} else if !condition.b {
				vm.jump(frame, instruction.Target, instruction.Span)
			}
		}
	case opNew:
		vm.executeNew(frame, instruction)
	case opCall:
		vm.executeCall(instruction)
	case opReturn:
		vm.executeReturn(instruction)
	case opCaseSelect:
		vm.executeCase(frame, instruction)
	case opHalt:
		vm.halted = true
		vm.paused = false
	default:
		vm.fail("COL6008", "unknown VM opcode "+string(instruction.Op), "Regenerate the program bytecode.", instruction.Span)
	}
	vm.record(string(instruction.Op), instruction.Span, vm.lastNote)
}
